#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'parse5';
import matter from 'gray-matter';
import { markdownAST, nodesOf } from './import-toml-1.1.0.mjs';
import {
  TOML_PAGE_MAP,
  TOML_SPECIFICATION_HEADINGS,
  TOML_VERSION_ID,
} from './toml-1.1.0-page-map.mjs';
import { hashFile } from './safe-import-output.js';

const [workspace, language = 'en'] = process.argv.slice(2);
assert.ok(workspace && ['en', 'ja'].includes(language), 'workspaceとen/jaを指定してください');
const app = path.join(workspace, 'apps/toml');
const base = `/docs/toml/${TOML_VERSION_ID}/${language}/`;
const walk = (node) => [node, ...(node.childNodes ?? []).flatMap(walk)];
const attribute = (node, name) => node.attrs?.find((item) => item.name === name)?.value;
const text = (node) => node.value ?? (node.childNodes ?? []).map(text).join('');
const documents = new Map();
for (const page of TOML_PAGE_MAP) {
  const slug = page.id.replace(/\.md$/, '');
  const file = path.join(app, 'dist', TOML_VERSION_ID, language, slug, 'index.html');
  const nodes = walk(parse(fs.readFileSync(file, 'utf8')));
  const article = nodes.find((node) => node.tagName === 'article');
  assert.ok(article, `${slug}: articleなし`);
  const ids = nodes.map((node) => attribute(node, 'id')).filter(Boolean);
  assert.equal(new Set(ids).size, ids.length, `${slug}: ID重複`);
  const codes = nodesOf(
    markdownAST(
      matter(
        fs.readFileSync(
          path.join(app, 'src/content/docs', TOML_VERSION_ID, language, page.id),
          'utf8'
        )
      ).content
    ),
    'code'
  );
  const renderedCodes = walk(article)
    .filter((node) => node.tagName === 'pre')
    .map(text);
  assert.deepEqual(
    renderedCodes,
    codes.map((node) => node.value),
    `${slug}: コード表示が本文と不一致`
  );
  documents.set(base + slug + '/', { page, file, nodes, article, ids, codes: codes.length });
}
let checkedInternalLinks = 0;
for (const [route, document] of documents) {
  for (const node of document.nodes.filter((entry) => entry.tagName === 'a')) {
    const href = attribute(node, 'href');
    if (!href || (!href.startsWith('#') && !href.startsWith(base))) continue;
    const url = new URL(href, `https://local.invalid${route}`);
    const pathname = `${url.pathname.replace(/\/$/, '')}/`;
    const target = documents.get(pathname);
    // The language index is generated by the application, outside the three source pages.
    if (pathname === base && !url.hash) {
      assert.ok(fs.existsSync(path.join(app, 'dist', TOML_VERSION_ID, language, 'index.html')));
    } else {
      assert.ok(target, `${route}: 内部リンク先なし ${href}`);
      if (url.hash)
        assert.ok(
          target.ids.includes(decodeURIComponent(url.hash.slice(1))),
          `${route}: アンカーなし ${href}`
        );
    }
    checkedInternalLinks++;
  }
}
const specification = documents.get(base + '01-specification/01-specification/');
for (const [, id] of TOML_SPECIFICATION_HEADINGS) {
  assert.ok(specification.ids.includes(`source-${id}`), `固定アンカーなし: ${id}`);
}
assert.deepEqual(
  [...documents.values()].map((document) => document.codes),
  [70, 1, 2]
);
console.log(
  JSON.stringify(
    {
      checkedAt: new Date().toISOString(),
      language,
      status: 'passed',
      pages: [...documents.values()].map((document) => ({
        id: document.page.id,
        htmlSha256: hashFile(document.file),
        codeBlocks: document.codes,
        ids: document.ids.length,
      })),
      checkedInternalLinks,
      stableSpecificationAnchors: TOML_SPECIFICATION_HEADINGS.length,
      codeTextMatchesMarkdown: true,
      fullAIContentReview: 'not-assessed-by-this-mechanical-check',
    },
    null,
    2
  )
);
