import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
const ev = 'docs/notes/project-expansion/runs/evidence/2026-10-04-654';
const trial = '/private/tmp/libx-mdbook-trial-654';
const clean = '/private/tmp/libx-jq-footer-integration-20261004';
const require = createRequire(clean + '/package.json');
const { parseFragment } = require('parse5');
const { createMarkdownProcessor } = await import(clean + '/node_modules/.pnpm/@astrojs+markdown-remark@6.3.1/node_modules/@astrojs/markdown-remark/dist/index.js');
const processor = await createMarkdownProcessor({ syntaxHighlight: false });
const sha = data => createHash('sha256').update(data).digest('hex');
const boundary = JSON.parse(fs.readFileSync('docs/notes/project-expansion/runs/evidence/2026-10-04-651/MDBOOK_BOUNDARY.json'));
assert.equal(boundary.records.filter(x => x.role === 'adopt').length, 31);
const flat = n => [n, ...(n.childNodes ?? []).flatMap(flat)];
const attr = (n, k) => n.attrs?.find(a => a.name === k)?.value;
const text = n => n.value ?? (n.childNodes ?? []).map(text).join('');
// Preserve all elements, ordered attributes, comments and content text exactly.
// Astro normalizes blank newlines at block boundaries; only whitespace children of root/div/main are ignored, never code/pre/style or inline content.
const shape = n => ({ name: n.nodeName, ...(n.value !== undefined ? { value: n.value } : {}), ...(n.data !== undefined ? { data: n.data } : {}), ...(n.attrs ? { attrs: n.attrs } : {}), children: (n.childNodes ?? []).filter(c => !(["#document-fragment", "div", "main"].includes(n.nodeName) && c.nodeName === "#text" && /^\s*$/.test(c.value))).map(shape) });
const records = [];
fs.mkdirSync(trial + '/astro-html', { recursive: true });
for (const entry of boundary.records.filter(x => x.role === 'adopt')) {
  const sourcePath = entry.path.replace(/^guide\/src\//, '');
  const outputPath = sourcePath.replace(/README\.md$/, 'index.md');
  const htmlPath = outputPath.replace(/\.md$/, '.html');
  const mdPath = trial + '/source/guide/book/markdown/' + outputPath;
  assert(fs.existsSync(mdPath), mdPath);
  const html = fs.readFileSync(trial + '/source/guide/book/html/' + htmlPath, 'utf8');
  assert.equal((html.match(/<main>/g) ?? []).length, 1);
  assert.equal((html.match(/<\/main>/g) ?? []).length, 1);
  const inner = html.slice(html.indexOf('<main>') + 6, html.indexOf('</main>')).trim();
  const protectedInner = inner.replace(/<pre\b[^>]*>[\s\S]*?<\/pre>/g, block => block.replace(/\n/g, '&#10;'));
  const input = '<div class="mdbook-guide">\n' + protectedInner + '\n</div>\n';
  const before = parseFragment('<div class="mdbook-guide">\n' + inner + '\n</div>\n');
  assert.deepEqual(shape(parseFragment(input)), shape(before), "newline encoding changed content");
  const rendered = await processor.render(input);
  const after = parseFragment(rendered.code);
  assert.deepEqual(shape(after), shape(before), 'Astro raw HTML structure difference: ' + sourcePath);
  const file = trial + '/astro-html/' + htmlPath;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, rendered.code);
  const nodes = flat(before);
  const code = nodes.filter(n => n.nodeName === 'code' && n.parentNode?.nodeName === 'pre');
  const headings = nodes.filter(n => /^h[1-6]$/.test(n.nodeName));
  const links = nodes.filter(n => n.nodeName === 'a' && attr(n, 'href')).map(n => ({ href: attr(n, 'href'), text: text(n) }));
  records.push({ sourcePath: entry.path, sourceSha256: entry.sha256, markdownPath: outputPath, markdownBytes: fs.statSync(mdPath).size, markdownSha256: sha(fs.readFileSync(mdPath)), htmlPath, mainSha256: sha(inner), astroSha256: sha(rendered.code), structuralComparison: 'exact-elements-ordered-attributes-comments-content-text; block-boundary-whitespace-only-normalized', headings: headings.map(n => ({ level: Number(n.nodeName.slice(1)), id: attr(n, 'id'), text: text(n) })), code: code.map(n => ({ class: attr(n, 'class'), text: text(n), sha256: sha(text(n)) })), links, images: nodes.filter(n => n.nodeName === 'img').map(n => ({ src: attr(n, 'src'), alt: attr(n, 'alt') })), svgCount: nodes.filter(n => n.nodeName === 'svg').length, tables: nodes.filter(n => n.nodeName === 'table').length, proseWordsIncludingCode: text(before).trim().split(/\s+/).length });
}
const totals = Object.fromEntries(['code','links','headings','images'].map(k => [k,records.reduce((n,r)=>n+r[k].length,0)]));
totals.tables = records.reduce((n,r)=>n+r.tables,0);
totals.svg = records.reduce((n,r)=>n+r.svgCount,0);
totals.wordsIncludingCode = records.reduce((n,r)=>n+r.proseWordsIncludingCode,0);
const data = { status:'passed-raw-html-Astro-processor-interoperability-only', version:'0.5.4', commit:boundary.commit, pages:records.length, totals, normalPage:'guide/src/guide/creating.md', largestPage:[...records].sort((a,b)=>b.markdownBytes-a.markdownBytes)[0].sourcePath, hardPages:['guide/src/format/mdbook.md','guide/src/format/mathjax.md','guide/src/for_developers/preprocessors.md'], fullContentReviewPerformed:false, conversionGatePassed:false, remaining:['Libx actual template build and local display', 'links and anchors remapping', 'hidden lines/editor/playground/math behavior and per-page assets', 'preferred editable source offer closure', 'Japanese research and measured cost/score/separate selection'], records };
fs.writeFileSync(ev + '/ASTRO_PROCESSOR_TRIAL_v3.json', JSON.stringify(data,null,2)+'\n', { flag:'wx' });
console.log(JSON.stringify({status:data.status,pages:data.pages,largestPage:data.largestPage,totals}));
